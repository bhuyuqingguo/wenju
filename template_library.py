def extra_catalog():
 result=[]
 for group_index,(category,(profile,rows)) in enumerate(GROUPS.items()):
  for index,row in enumerate(rows.splitlines()):
   name,outline=row.split('|');p=PROFILES[profile]
   result.append(dict(id=f'scene-{group_index+1:02}-{index+1:02}',name=name,category=category,
     desc=outline+'。',outline=outline,profile=profile,redhead=category=='红头文件',**p))
 return result

def apply_profile(r,t):
 p=PROFILES[t['profile']]
 r['页面'].update(dict(zip(('上边距','下边距','左边距','右边距'),p['margins'])))
 r['标题']['级数']=p['levels'];r['表格']['字号']=p['table']
 r['正文']['行距类型']='固定值'
 if t['profile']=='official':
  r['公文']['启用']=True
  for level in ('一级','二级','三级'):r['标题'][level]['字号']=16
  r['字体']['二级标题']='楷体_GB2312'
  r['题注']['缺失时自动补编号']=False
 if t.get('redhead'):
  r['红头']['启用']=True
 return r
